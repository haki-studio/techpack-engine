def md():
    out = [f"# Pixel Sky fleece ({P.STYLE}) — what is still TBD in Rev G ({P.DATE})", "",
           "Send-ready: every item below is printed in the RFQ pack as [proposed — confirm] or as a factory question, so none blocks sending.", ""]
    for g, rows in GROUPS:
        out += [f"## {g}", ""] + [f"- **{a}:** {b}" for a, b in rows] + [""]
    return "\n".join(out)

def png(path):
    SHT.FOOT = P.SHT.FOOT
    o = SHT.header("WHAT IS STILL TBD — Rev G", "Every item is printed in the RFQ pack as [proposed — confirm] or asked as a factory question, so none blocks sending.", "TBD")
    y = 33
    for g, rows in GROUPS:
        o.append(t(12, y, g, 2.2, 700, RED if g.startswith("DECIDED BY US") else INK)); y += 4.2
        for a, b in rows:
            o.append(t(14, y, a, 1.6, 700)); y = P.para(o, 58, y, b, 150, 1.5, INK, 2.75) + 0.7
        y += 2.5
    cairosvg.svg2png(bytestring=doc(o).encode(), write_to=path, output_width=2400)
    return y

